df.head()



import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

df.shape

"""here we checked the size of data"""

df.info()
df.describe().T

"""The dataset contains 207 countries. country and region are categorical identification variables, while the remaining columns contain numerical demographic, social and economic information."""

missing = pd.DataFrame({
    "Missing values": df.isnull().sum(),
    "Missing percentage": (df.isnull().mean() * 100).round(1)
})

missing.sort_values("Missing percentage", ascending=False)

"""this checks missing values"""

features = [
    "tfr",
    "contraception",
    "lifeMale",
    "lifeFemale",
    "infantMortality",
    "GDPperCapita",
    "illiteracyMale",
    "illiteracyFemale"
]

X = df[features].copy()

"""Country and region were excluded because PCA and K-Means require numerical variables. EducationMale and educationFemale were excluded because approximately 63% of their observations are missing. The economic-activity variables were excluded to keep the analysis focused on the main demographic, health, literacy and economic indicators associated with national development."""

plt.figure(figsize=(14, 8))

for i, column in enumerate(features, 1):
    plt.subplot(2, 4, i)
    sns.boxplot(y=X[column])
    plt.title(column)

plt.tight_layout()
plt.show()

outlier_counts = {}

for column in features:
    Q1 = X[column].quantile(0.25)
    Q3 = X[column].quantile(0.75)
    IQR = Q3 - Q1

    outliers = X[
        (X[column] < Q1 - 1.5 * IQR) |
        (X[column] > Q3 + 1.5 * IQR)
    ]

    outlier_counts[column] = len(outliers)

pd.Series(outlier_counts, name="Potential outliers")

"""The boxplots and IQR rule identified several potential outliers. These observations were retained because they represent real countries with meaningful demographic or economic characteristics rather than data-entry errors. Removing them could eliminate relevant groups of countries. Their possible influence is considered when interpreting the clusters."""

X_imputed = X.fillna(X.median())

X_imputed.isnull().sum()

"""Missing numerical values were replaced with the median of each variable. The median is less influenced by extreme values than the mean and allows all countries to remain in the analysis."""

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_imputed)

X_scaled = pd.DataFrame(
    X_scaled,
    columns=features,
    index=df.index
)

X_scaled.head()

pd.DataFrame({
    "Mean": X_scaled.mean(),
    "Standard deviation": X_scaled.std(ddof=0)
}).round(3)

"""Standardization is necessary because the variables use very different scales. For example, GDP per capita has much larger numerical values than fertility or life expectancy. Without standardization, variables with large values would have an excessive influence on PCA and K-Means."""

pca = PCA()
X_pca_all = pca.fit_transform(X_scaled)

explained_variance = pca.explained_variance_ratio_
cumulative_variance = np.cumsum(explained_variance)

variance_table = pd.DataFrame({
    "Component": range(1, len(features) + 1),
    "Explained variance (%)": explained_variance * 100,
    "Cumulative variance (%)": cumulative_variance * 100
})

variance_table.round(2)

n_components_90 = np.argmax(cumulative_variance >= 0.90) + 1
n_components_90

"""here we determine the number needed for at least 90%:"""

pca_final = PCA(n_components=n_components_90)
X_pca = pca_final.fit_transform(X_scaled)

fig, ax1 = plt.subplots(figsize=(9, 5))

ax1.bar(
    range(1, len(explained_variance) + 1),
    explained_variance * 100,
    color="steelblue",
    alpha=0.7
)
ax1.set_xlabel("Principal component")
ax1.set_ylabel("Individual explained variance (%)")

ax2 = ax1.twinx()
ax2.plot(
    range(1, len(cumulative_variance) + 1),
    cumulative_variance * 100,
    color="darkred",
    marker="o"
)
ax2.axhline(90, color="gray", linestyle="--")
ax2.set_ylabel("Cumulative explained variance (%)")

plt.title("PCA Explained Variance")
plt.show()

loadings = pd.DataFrame(
    pca_final.components_.T,
    index=features,
    columns=[f"PC{i}" for i in range(1, n_components_90 + 1)]
)

loadings.round(3)

for component in loadings.columns:
    print(component)
    print(loadings[component].sort_values(key=abs, ascending=False))
    print()

"""PC1 explains approximately 70.2% of the variance and represents a broad development and health dimension. Life expectancy and contraception are positioned in the opposite direction from fertility, infant mortality and illiteracy. PC2 explains approximately 12.6% and is influenced mainly by GDP per capita and literacy-related differences. Four components retain approximately 95.3% of the original information, so PCA provides meaningful dimensionality reduction."""

k_values = range(2, 9)

inertias = []
silhouette_scores = []

for k in k_values:
    model = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=50
    )

    labels = model.fit_predict(X_pca)

    inertias.append(model.inertia_)
    silhouette_scores.append(
        silhouette_score(X_pca, labels)
    )

evaluation = pd.DataFrame({
    "k": list(k_values),
    "Inertia": inertias,
    "Silhouette score": silhouette_scores
})

evaluation.round(3)

fig, axes = plt.subplots(1, 2, figsize=(13, 5))

axes[0].plot(k_values, inertias, marker="o")
axes[0].set_title("Elbow Method")
axes[0].set_xlabel("Number of clusters")
axes[0].set_ylabel("Inertia")
axes[0].grid(True)

axes[1].plot(k_values, silhouette_scores, marker="o", color="darkorange")
axes[1].set_title("Silhouette Scores")
axes[1].set_xlabel("Number of clusters")
axes[1].set_ylabel("Silhouette score")
axes[1].grid(True)

plt.tight_layout()
plt.show()

"""The silhouette score is highest for two clusters, showing that the broad developed/developing division is visible in the data. However, the elbow curve continues to improve substantially until approximately four clusters. Four clusters reveal meaningful intermediate development groups that are hidden by the two-cluster solution. Therefore, four clusters were chosen as the preferred interpretation, while recognizing that two clusters provide the clearest statistical separation."""

kmeans_2 = KMeans(
    n_clusters=2,
    random_state=42,
    n_init=50
)

kmeans_4 = KMeans(
    n_clusters=4,
    random_state=42,
    n_init=50
)

labels_2 = kmeans_2.fit_predict(X_pca)
labels_4 = kmeans_4.fit_predict(X_pca)

"""now we Compare two and four clusters"""

inertia_reduction = (
    (kmeans_2.inertia_ - kmeans_4.inertia_) /
    kmeans_2.inertia_
) * 100

round(inertia_reduction, 2)

"""Moving from two to four clusters reduces within-cluster variation by approximately 42.6%. This indicates that the four-cluster solution captures considerably more detail, although its silhouette score is lower."""

results = df[["country", "region"]].copy()
results["cluster_2"] = labels_2
results["cluster_4"] = labels_4

results.head()

for cluster in sorted(results["cluster_4"].unique()):
    print(f"\nCluster {cluster}")
    print(
        results.loc[
            results["cluster_4"] == cluster,
            "country"
        ].tolist()
    )

cluster_profiles = X_imputed.copy()
cluster_profiles["cluster"] = labels_4

cluster_profiles.groupby("cluster").median().round(2)

"""The four clusters should contain approximately:
- 100 countries
- 37 countries
- 32 countries
- 38 countries
The cluster numbers may appear in another order. That is normal.
"""

representatives = []

for cluster in range(4):
    indices = np.where(labels_4 == cluster)[0]

    distances = np.linalg.norm(
        X_pca[indices] -
        kmeans_4.cluster_centers_[cluster],
        axis=1
    )

    representative_index = indices[np.argmin(distances)]

    representatives.append({
        "Cluster": cluster,
        "Country": df.loc[representative_index, "country"],
        "Region": df.loc[representative_index, "region"]
    })

representatives = pd.DataFrame(representatives)
representatives

